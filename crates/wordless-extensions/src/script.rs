    #[test]
    fn shim_exposes_enqueue_methods_as_recorded_only() {
        let input = ExtensionProjectInput {
            slug: "hello-dolly",
            version: "1.7.2",
            files: &[ConvertedFile {
                path: "hello.php".to_string(),
                generated_path: "extensions/hello-dolly/converted/hello.ts".to_string(),
                code: hello_dolly_code(),
            }],
            declared_hosts: &[],
            locale: "en_US",
        };
        let project = generate_extension_project(&input);
        // The shim must expose both enqueue methods so converted theme
        // code (TT25) can call them synchronously; denials are
        // swallowed in the shim because the host endpoint logs them.
        assert!(project.shim.contains("wp_enqueue_style:"));
        assert!(project.shim.contains("wp_enqueue_script:"));
        assert!(project.shim.contains("hostCall(\"wp_enqueue_style\""));
        assert!(project.shim.contains("hostCall(\"wp_enqueue_script\""));
        assert!(project.shim.contains(".catch(() => {})"));
        assert!(project.wordpress_dts[0]
            .1
            .contains("wp_enqueue_style(handle: string"));
        assert!(project.wordpress_dts[0]
            .1
            .contains("wp_enqueue_script(handle: string"));
    }

    #[test]
    fn nested_paths_and_slug_sanitising() {
        let input = ExtensionProjectInput {
            slug: "My_Plugin v2",
            version: "0.1",
            files: &[ConvertedFile {
                path: "inc/foo.php".to_string(),
                generated_path: "extensions/x/converted/inc/foo.ts".to_string(),
                code: "export function activate(wp: WordPressApi): void {}\n".to_string(),
            }],
            declared_hosts: &["api.example.com".to_string()],
            locale: "en_US",
        };
        let project = generate_extension_project(&input);
        assert_eq!(
            project.converted_paths,
            vec!["converted/inc/foo.ts".to_string()]
        );
        assert!(project.wrangler_toml.contains("name = \"my-plugin-v2\""));
        assert!(project.shim.contains("api.example.com"));
        assert!(project.entry.contains("converted/inc/foo.js"));
        assert!(project.wordpress_dts.is_empty()); // no type import in this file
    }

    #[test]
    fn shim_has_no_credentials_baked_in() {
        let input = ExtensionProjectInput {
            slug: "x",
            version: "1",
            files: &[],
            declared_hosts: &[],
            locale: "en_US",
        };
        let project = generate_extension_project(&input);
        // The token is read from the per-invocation context only — it is
        // never a literal in the script. A stolen script contains no
        // credentials. The only token literal in the shim is the empty
        // default of the initial invocation context.
        assert!(project.shim.contains("ctx.hostToken"));
        assert!(project.shim.contains("hostToken: \"\""));
        assert!(!project.shim.contains("hostToken: \"tok"));
        assert!(!project.entry.contains("hostToken: \"tok"));
    }
